package ru.nsu.oop.model;

/**
 * Запечатанный базовый интерфейс для всех учебных записей в зачетной книжке. Гарантирует, что в
 * системе могут существовать только строго определенные типы записей (с оценкой или с зачетом),
 * предотвращая появление невалидных состояний.
 */
public sealed interface StudyRecord permits GradedStudyRecord, CreditStudyRecord {

    /**
     * Возвращает название учебной дисциплины.
     *
     * @return название предмета
     */
    String subjectName();
}
