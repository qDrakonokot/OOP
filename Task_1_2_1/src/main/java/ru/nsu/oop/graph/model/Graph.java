package ru.nsu.oop.graph.model;

import java.util.List;


/**
 * Интерфейс, представляющий направленный граф. Позволяет хранить вершины любого ссылочного типа T и
 * управлять связями между ними.
 *
 * @param <T> тип данных, хранящихся в вершинах графа
 */
public interface Graph<T> {

    /**
     * Добавляет новую вершину в граф. Если вершина уже существует, операция игнорируется.
     *
     * @param vertex вершина для добавления
     */
    void addVertex(T vertex);

    /**
     * Добавляет направленное ребро между двумя вершинами. Если вершины отсутствуют в графе, они
     * будут созданы автоматически.
     *
     * @param from исходная вершина (откуда исходит ребро)
     * @param to   целевая вершина (куда входит ребро)
     * @throws IllegalArgumentException если from и to совпадают (петли запрещены)
     */
    void addEdge(T from, T to);

    /**
     * Возвращает список всех вершин, в которые есть исходящие ребра из заданной вершины.
     *
     * @param vertex вершина, соседей которой нужно найти
     * @return неизменяемый список соседних вершин (может быть пустым, если соседей нет)
     */
    List<T> getNeighbours(T vertex);

    /**
     * Возвращает список всех вершин, существующих в графе.
     *
     * @return неизменяемый список всех вершин
     */
    List<T> getVertexesList();

    /**
     * Удаляет вершину из графа, а также все входящие и исходящие ребра, связанные с ней. Если
     * вершины нет в графе, операция игнорируется.
     *
     * @param vertex вершина для удаления
     */
    void deleteVertex(T vertex);

    /**
     * Удаляет направленное ребро между двумя вершинами. Если ребра или самих вершин не существует,
     * операция игнорируется.
     *
     * @param from исходная вершина
     * @param to   целевая вершина
     */
    void deleteEdge(T from, T to);
}
